/** Small CSV/TSV reader for on-screen preview only. Handles quotes, escaped quotes and line breaks inside quotes. */
export function parseDelimited(text: string, delimiter = ",", maxRows = 200): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = "";
  let quoted = false;
  const src = text.replace(/^\uFEFF/, "");
  for (let i = 0; i < src.length && rows.length < maxRows; i++) {
    const c = src[i];
    if (quoted) {
      if (c === '"' && src[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"' && cell === "") quoted = true;
    else if (c === delimiter) { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && src[i + 1] === "\n") i++;
      row.push(cell); cell = "";
      if (row.some((v) => v.trim() !== "")) rows.push(row);
      row = [];
    } else cell += c;
  }
  if (rows.length < maxRows && (cell !== "" || row.length)) { row.push(cell); if (row.some((v) => v.trim() !== "")) rows.push(row); }
  return rows;
}
