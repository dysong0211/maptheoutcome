import {
  cp,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  symlink,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scratch = await mkdtemp(join(tmpdir(), "maptoc-website-build-"));
const output = join(root, "dist", "website");
const marker = ".maptoc-generated";
try {
  // Isolate Next's build files from the running local demo.
  for (const name of [
    "src",
    "package.json",
    "next.config.ts",
    "postcss.config.mjs",
    "tsconfig.json",
    "next-env.d.ts",
  ]) {
    await cp(join(root, name), join(scratch, name), { recursive: true });
  }
  await symlink(
    join(root, "node_modules"),
    join(scratch, "node_modules"),
    "dir",
  );
  // Static demo has no server. Omit API routes only from the disposable copy;
  // the live integration remains available in the local Next server app.
  await rm(join(scratch, "src", "app", "api"), { recursive: true, force: true });
  const result = spawnSync(
    process.execPath,
    [join(root, "node_modules/next/dist/bin/next"), "build"],
    {
      cwd: scratch,
      env: {
        ...process.env,
        MAPTOC_STATIC_EXPORT: "1",
        NEXT_PUBLIC_LIGHT_DEMO: "1",
        NEXT_TELEMETRY_DISABLED: "1",
      },
      stdio: "inherit",
    },
  );
  if (result.error) throw result.error;
  if (result.status !== 0)
    throw new Error("Demo export failed; website output was not changed.");

  // Remove only an output previously created by this script.
  try {
    await readFile(join(output, marker));
    await rm(output, { recursive: true });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  await mkdir(output, { recursive: true });
  await cp(join(root, "website"), output, { recursive: true });
  await cp(join(scratch, "out"), join(output, "demo"), { recursive: true });
  // Some simple static servers show a directory listing for /demo/ instead of
  // resolving index.html. Use an explicit file URL in generated site links.
  for (const name of ["index.html", "white-paper.html", "research.html", "vision.html"]) {
    const file = join(output, name);
    try {
      const html = await readFile(file, "utf8");
      await writeFile(file, html.replaceAll('href="demo/"', 'href="demo/index.html"'));
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  await writeFile(join(output, ".nojekyll"), "");
  await writeFile(
    join(output, marker),
    "Generated by scripts/build-website.mjs\n",
  );
  console.log(`Website and demo ready: ${output}`);
} finally {
  await rm(scratch, { recursive: true, force: true });
}
