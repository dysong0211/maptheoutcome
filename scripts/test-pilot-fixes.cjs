require('./test-evidence.cjs');
const assert=require('node:assert/strict');
const {useMemoryStore:store}=require('../src/stores/program-memory-store.ts');
const {useDemoStore:roles}=require('../src/stores/demo-store.ts');
const {defaultReportPeriod}=require('../src/lib/report-draft.ts');
roles.getState().setRole('program'); store.getState().reset();
const snapshot=localStorage.getItem('maptoc-program-memory-v1');
const other=JSON.parse(snapshot);other.state.sources.unshift({id:'tab-a',title:'Other tab',passages:[]});other.state.events.unshift({id:'tab-a-event'});
localStorage.setItem('maptoc-program-memory-v1',JSON.stringify(other));
assert.ok(!store.getState().sources.some(s=>s.id==='tab-a'),'simulate old in-memory tab');
assert.equal(store.getState().addCapturedSource({id:'tab-b',title:'This tab',passages:[],capturedAt:new Date().toISOString()}),true);
const saved=JSON.parse(localStorage.getItem('maptoc-program-memory-v1')).state;
assert.ok(saved.sources.some(s=>s.id==='tab-a'));assert.ok(saved.sources.some(s=>s.id==='tab-b'));assert.ok(saved.events.some(e=>e.id==='tab-a-event'));
assert.equal(store.getState().addCapturedSource({id:'tab-a',title:'Duplicate',passages:[]}),false);
assert.ok(!saved.events[0].actor.includes('Maya'));
assert.equal(defaultReportPeriod([], '2026-12-31','2026-11-24').to,'2026-11-24');
assert.equal(defaultReportPeriod([{eventDate:'2026-12-02'}], '2026-12-31','2026-11-24').to,'2026-11-24');
assert.equal(defaultReportPeriod([{eventDate:'2026-11-20'}], '2026-12-31','2026-11-24').to,'2026-11-20');
console.log('Pilot fixes passed: stale tab preserves other evidence/events, duplicate guard refreshed, neutral capture actor, report defaults exclude future dates.');
