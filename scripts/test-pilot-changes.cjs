// Update plan: revisions change the current plan, never the original.
{
  const {currentPlan,indicatorStatus:st}=require('../src/stores/tracking-store.ts');
  const b={id:'i',programId:'p',name:'n',unit:'',breakdown:[],baseline:0,target:100,baselineDate:'2026-01-01',targetDate:'2026-12-31',latest:40,latestDate:'2026-07-02'};
  assert.equal(st(b),'Behind');
  const r={...b,revisions:[{id:'r1',at:'2026-07-03T00:00:00Z',reason:'Floods delayed delivery',target:60,targetDate:'2027-06-30'}]};
  assert.equal(r.target,100,'original target kept');assert.equal(r.targetDate,'2026-12-31');
  assert.deepEqual(currentPlan(r),{target:60,targetDate:'2027-06-30',revised:true});
  assert.equal(st(r),'On track','against the revised plan 40 is on the line');
  assert.equal(currentPlan(b).revised,false);
  const d={...b,revisions:[{id:'r1',at:'x',reason:'a',targetDate:'2027-12-31'}]};
  assert.equal(currentPlan(d).target,100,'a date-only change keeps the target');
}
