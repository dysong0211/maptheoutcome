require('./test-evidence.cjs');
const assert=require('node:assert/strict');
const {validateProgram}=require('../src/lib/program-assurance.ts');
const {programIdLine}=require('../src/lib/program-ids.ts');
const {createProgramExample}=require('../src/lib/program-assurance-examples.ts');
const base=createProgramExample('health','program-test').program;
assert.doesNotThrow(()=>validateProgram(base),'existing programs without IDs stay valid');
assert.doesNotThrow(()=>validateProgram({...base,programRef:'UNDP-2026-001',grantRef:'GR/445'}));
assert.throws(()=>validateProgram({...base,grantRef:'x'.repeat(201)}),/200 characters/);
assert.equal(programIdLine({programRef:' P1 ',grantRef:'G2'}),'Program ID P1 · Grant ID G2');
assert.equal(programIdLine({}),'');assert.equal(programIdLine(undefined),'');
console.log('Program/grant ID checks passed.');
const {useMemoryStore:ms}=require('../src/stores/program-memory-store.ts');
const {cleanTags}=require('../src/lib/program-memory.ts');
assert.deepEqual(cleanTags({outputCode:' 1.2 ',activityCode:'',partner:'  NGO A',location:'x'.repeat(100)}),{outputCode:'1.2',partner:'NGO A',location:'x'.repeat(80)});
assert.throws(()=>validateProgram({...base,agreementStart:'2026-13-01'}),/agreement dates/);
assert.throws(()=>validateProgram({...base,agreementStart:'2026-05-01',agreementEnd:'2026-01-01'}),/after its start/);
assert.doesNotThrow(()=>validateProgram({...base,agreementStart:'2026-01-01',agreementEnd:'2026-12-31',grantRef:'G1, G2'}));
console.log('Tracking tag and agreement date checks passed.');
const {useDemoStore:roles2}=require('../src/stores/demo-store.ts');
roles2.getState().setRole('program');ms.getState().reset();ms.getState().importSample();roles2.getState().setRole('reviewer');
const pid=ms.getState().proposals[0].id;
assert.equal(ms.getState().review(pid,'approved','Checked wording','Checked source',false,{outputCode:'OUT-1.2',partner:'Partner A'}),true);
const rec=ms.getState().records.find(r=>r.proposalId===pid);
assert.equal(rec.outputCode,'OUT-1.2');assert.equal(rec.partner,'Partner A');assert.ok(rec.location);
console.log('Review applies tracking tags to the approved record.');
