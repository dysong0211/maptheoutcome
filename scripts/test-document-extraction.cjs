require('./test-evidence.cjs');
const assert = require('node:assert/strict');
const { extractDocument } = require('../src/lib/document-extraction.ts');
(async () => {
  const text = await extractDocument(new File(['Attendance: 42'], 'notes.txt'), 'text');
  assert.equal(text.passages[0].text, 'Attendance: 42');
  assert.equal(text.passages[0].id, 'text-p1');
  const limited = await extractDocument(new File(['a'.repeat(50001)], 'long.txt'), 'long');
  assert.equal(limited.passages[0].text.length, 50000);
  assert.match(limited.note, /limited/);
  const excel = require('exceljs');
  const workbook = new excel.Workbook();
  workbook.addWorksheet('District A').addRow(['Women reached', 1240]);
  const sheet = await extractDocument(new File([await workbook.xlsx.writeBuffer()], 'data.xlsx'), 'sheet');
  assert.match(sheet.passages[0].locator, /District A.*row 1/);
  assert.match(sheet.passages[0].text, /B1: 1240/);
  const JSZip = require('node:module').createRequire(require.resolve('exceljs'))('jszip');
  const zip = new JSZip();
  zip.file('[Content_Types].xml', '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>');
  zip.file('_rels/.rels', '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>');
  zip.file('word/document.xml', '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>Saturday outreach</w:t></w:r></w:p></w:body></w:document>');
  const docx = await extractDocument(new File([await zip.generateAsync({type:'uint8array'})], 'report.docx'), 'word');
  assert.equal(docx.passages[0].text, 'Saturday outreach');
  assert.match(docx.passages[0].locator, /Word paragraph 1/);
  const broken = await extractDocument(new File(['broken zip'], 'broken.docx'), 'broken');
  assert.equal(broken.passages.length, 0);
  assert.match(broken.note, /extraction failed/);
  const image = await extractDocument(new File(['image'], 'scan.jpg'), 'image');
  assert.equal(image.passages.length, 0);
  assert.match(image.note, /AI reading/);
  const legacy = await extractDocument(new File(['legacy'], 'report.doc'), 'legacy');
  assert.match(legacy.note, /export as DOCX/);
  console.log('Document extraction passed: text, truncation, real XLSX, corrupt DOCX, image and legacy fallback.');
})().catch(error => { console.error(error); process.exitCode = 1; });
