require('./test-evidence.cjs');
const assert = require('node:assert/strict');
const { assuranceInbox, summarizeChecks } = require('../src/lib/assurance-overview.ts');
const { allEvidence, controlInputs, fingerprint } = require('../src/lib/assurance.ts');
const { initialSources } = require('../src/lib/program-memory.ts');
const workspace = { controls: [{id:'transport-approval',title:'Approval check',status:'confirmed',version:1}], runs:[], findings:[], audit:[], addedSources:[] };
assert.deepEqual(summarizeChecks(workspace,initialSources),{total:1,tested:0,stale:0,latest:undefined,supported:0,review:0,unable:1});
workspace.runs.push({id:'run',controlId:'transport-approval',controlVersion:1,time:'2026-10-01T00:00:00Z',fingerprint:fingerprint(controlInputs('transport-approval',allEvidence(workspace,initialSources))), explanation:'Amount approval needs review.',sources:[]});
assert.equal(summarizeChecks(workspace,initialSources).stale,0);
workspace.runs[0].outcome='Passed';
assert.equal(summarizeChecks(workspace,initialSources).supported,1);
workspace.runs[0].outcome='Unable to test';
assert.equal(summarizeChecks(workspace,initialSources).unable,1);
assert.equal(summarizeChecks(workspace,initialSources).supported,0);
workspace.runs[0].outcome='Potential exception';
assert.equal(summarizeChecks(workspace,initialSources).review,1);
workspace.controls[0].version=2;
assert.equal(summarizeChecks(workspace,initialSources).stale,1,'A scope version change requires retesting');
assert.equal(summarizeChecks(workspace,initialSources).supported,0,'Stale checks cannot count as supported');
workspace.findings.push({id:'finding',controlId:'transport-approval',latestRunId:'run',status:'assigned',owner:'Demo reviewer',due:'2026-10-03',requestOpen:false});
const tasks = [{id:'me-check',due:'2026-09-22'}];
const rows = assuranceInbox(workspace,initialSources,tasks,[],{},'2026-10-05');
assert.ok(rows.some(r=>r.id==='finding' && r.owner==='Demo reviewer' && r.overdue));
assert.ok(rows.some(r=>r.id==='stale-checks'),'Stale checks must not hide open findings');
assert.equal(rows.find(r=>r.id==='cost-followup').overdue,false,'No due date is not overdue');
assert.equal(rows.find(r=>r.id==='attendance').overdue,true);
assert.equal(assuranceInbox(workspace,initialSources,tasks,[],{},'').find(r=>r.id==='attendance').overdue,false,'No clock means unknown, not overdue');
workspace.findings[0].status='closed';
const completed = assuranceInbox(workspace,initialSources,tasks,[{id:'attendance',sourceId:initialSources[0].id}],{'referrals':true},'2026-10-05');
assert.ok(!completed.some(r=>r.id==='finding'));
assert.equal(completed.find(r=>r.id==='attendance').stage,'review','Receipt needs review, not automatic closure');
assert.ok(completed.some(r=>r.id==='referrals'),'Task checkmarks do not resolve evidence gaps');
assert.ok(assuranceInbox(workspace,[],tasks,[{id:'attendance',sourceId:'missing'}],{},'2026-10-05').some(r=>r.id==='attendance'),'Unavailable linked source must remain a gap');
workspace.controls[0].status='proposed';
assert.equal(summarizeChecks(workspace,initialSources).total,0,'Proposals must not count as confirmed check coverage');
console.log('Assurance overview passed: scope freshness, open findings, closed exclusion, due dates, source availability and review separation.');
