require('./test-evidence.cjs');
const assert=require('node:assert/strict');
const {useMemoryStore:memory}=require('../src/stores/program-memory-store.ts');
const {useOutputStore:outputs,assessInputs}=require('../src/stores/output-intelligence-store.ts');
const {useDemoStore:roles}=require('../src/stores/demo-store.ts');
const {incomingSource}=require('../src/lib/program-memory.ts');
memory.getState().reset();outputs.getState().reset();roles.getState().setRole('program');
const count=memory.getState().records.length;
assert.equal(memory.getState().importSample(),true);
assert.equal(memory.getState().saveSourceReviews([incomingSource.id],'saved'),false);
for(const p of memory.getState().proposals)memory.getState().prepareProposal(p.id,'kept',p.statement);
assert.equal(memory.getState().saveSourceReviews([incomingSource.id],'saved'),true);
assert.equal(memory.getState().records.length,count);
const note={...incomingSource,id:'note-test',documentId:'note-test',title:'Test note',origin:'browser-upload',category:'program-design'};
assert.equal(memory.getState().addCapturedSource(note),true);
assert.equal(memory.getState().saveSourceReviews([note.id],'saved'),false);
assert.equal(memory.getState().saveSourceReviews([note.id],'repository-only'),true);
assert.equal(memory.getState().saveSourceReviews([note.id,incomingSource.id],'saved'),true);
outputs.getState().linkSource('attendance',note.id);
assert.equal(assessInputs(['attendance'],outputs.getState().requirements,memory.getState().sources)[0].missing,false);
assert.equal(memory.getState().removeSource(note.id),true);
assert.equal(assessInputs(['attendance'],outputs.getState().requirements,memory.getState().sources)[0].missing,true);
memory.persist.rehydrate();assert.ok(memory.getState().trashSources.find(s=>s.id===note.id));
assert.equal(memory.getState().restoreSource(note.id),true);
assert.equal(memory.getState().removeSource(memory.getState().records[0].citation.versionId),false);
assert.equal(outputs.getState().tasks.find(t=>t.id==='irb-submission').due,'2026-07-10');
assert.equal(outputs.getState().updateTask('irb-submission','IRB submission','2026-07-01','2026-07-12'),true);
assert.equal(outputs.getState().updateTask('irb-submission','IRB submission','2026-07-30','2026-07-12'),false);
assert.equal(outputs.getState().updateTask('irb-submission','IRB submission','2026-07-01','2026-07-12',['Revised protocol']),true);
const revised=outputs.getState().tasks.find(t=>t.id==='irb-submission');
assert.equal(outputs.getState().requirements.find(r=>r.id===revised.requirementIds[0]).label,'Revised protocol');
assert.ok(outputs.getState().requirements.find(r=>r.id==='protocol'),'Earlier requirement preserved');
roles.getState().setRole('funder');
assert.equal(memory.getState().removeSource(note.id),false);
assert.equal(memory.getState().saveSourceReviews([note.id],'repository-only'),false);
assert.equal(outputs.getState().updateTask('irb-submission','Changed','2026-07-01','2026-07-12'),false);
console.log('Source workflow passed: batch save, repository skip, triage, recovery, coverage, IRB, plan editing, role guards.');
