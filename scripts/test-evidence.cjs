// Exercise the real TypeScript store using a small CommonJS transpilation hook.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const ts = require("typescript");
const root = path.resolve(__dirname, "..");
const originalResolve = Module._resolveFilename;
Module._resolveFilename = function (request, ...args) {
  return originalResolve.call(this, request.startsWith("@/") ? path.join(root, "src", request.slice(2)) : request, ...args);
};
require.extensions[".ts"] = (module, filename) => {
  const result = ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } });
  module._compile(result.outputText, filename);
};
const memory = new Map();
global.localStorage = { getItem: (key) => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value), removeItem: (key) => memory.delete(key) };
global.window = { localStorage: global.localStorage };
const { useDemoStore: store } = require("../src/stores/demo-store.ts");
store.getState().resetDemo();
store.getState().setRole("funder");
const id = "evidence-q2-report";
const initial = store.getState().evidence.find((item) => item.id === id);
const initialEvents = store.getState().events.length;
store.getState().reviseEvidence(id, "Forbidden.pdf", "Funder attempt");
assert.equal(store.getState().events.length, initialEvents);
store.getState().setRole("program");
store.getState().reviseEvidence(id, "Revised.pdf", "Clarify six sites");
const revised = store.getState().evidence.find((item) => item.id === id);
assert.equal(revised.version, 3);
assert.equal(revised.history.at(-1).name, initial.name);
assert.equal(revised.history.at(-1).version, 2);
assert.equal(revised.history[0].version, 1);
assert.equal(initial.name, "Q2_Deployment_Report.pdf");
assert.equal(store.getState().events.length, initialEvents + 1);
assert.equal(store.getState().events[0].action, "EVIDENCE_REPLACED");
store.getState().mapEvidence(id, "outcome-access");
assert.equal(store.getState().events[0].action, "EVIDENCE_LINKED");
const count = store.getState().events.length;
store.getState().mapEvidence(id, "outcome-access");
store.getState().mapEvidence(id, "invalid-node");
store.getState().reviseEvidence(id, "", "");
assert.equal(store.getState().events.length, count);
assert.ok(memory.has("maptoc-investor-demo"), "Store must actually persist state");
const persisted = memory.get("maptoc-investor-demo");
store.getState().resetDemo();
memory.set("maptoc-investor-demo", persisted);
store.persist.rehydrate();
assert.equal(store.getState().evidence.find((item) => item.id === id).version, 3);
assert.equal(store.getState().events.length, count);
store.getState().setRole("program");
const originalNow = Date.now;
Date.now = () => 123456789;
store.getState().uploadEvidence({ name: "One.pdf", type: "PDF", size: "1 KB" });
store.getState().uploadEvidence({ name: "Two.pdf", type: "PDF", size: "1 KB" });
Date.now = originalNow;
assert.equal(new Set(store.getState().evidence.map((item) => item.id)).size, store.getState().evidence.length, "Rapid uploads must have unique IDs");
assert.equal(new Set(store.getState().events.map((item) => item.id)).size, store.getState().events.length, "Rapid events must have unique IDs");
store.getState().setRole("funder");
store.getState().uploadEvidence({ name: "Blocked.pdf", type: "PDF", size: "1 KB" });
assert.equal(store.getState().events.length, count + 2);
store.getState().resetDemo();
assert.equal(store.getState().evidence.find((item) => item.id === id).version, 2);
assert.equal(store.getState().events.length, initialEvents);
console.log("Evidence tests passed: role guards, version retention, mapping, duplicate suppression, unique upload IDs, persistence/rehydration, and reset.");
