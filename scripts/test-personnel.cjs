require('./test-evidence.cjs');
const assert = require('node:assert/strict');
const {usePersonnel: personnel} = require('../src/stores/personnel-store.ts');
const {useDemoStore: demo} = require('../src/stores/demo-store.ts');
const {useMemoryStore: memory} = require('../src/stores/program-memory-store.ts');
personnel.getState().reset();
demo.getState().setRole('funder');
assert.equal(personnel.getState().assign('attendance','Unauthorized'),false);
demo.getState().setRole('reviewer');
assert.equal(personnel.getState().assign('attendance','Unauthorized'),false);
demo.getState().setRole('program');
assert.equal(personnel.getState().assign('attendance','  Pilot M&E lead  '),true);
assert.equal(personnel.getState().owners.attendance,'Pilot M&E lead');
assert.equal(memory.getState().events[0].action,'UPLOAD_OWNER_ASSIGNED');
assert.equal(personnel.getState().assign('attendance','x'.repeat(81)),false);
const saved = localStorage.getItem('maptoc-upload-owners-v1');
personnel.getState().reset();
localStorage.setItem('maptoc-upload-owners-v1',saved);
personnel.persist.rehydrate();
assert.equal(personnel.getState().owners.attendance,'Pilot M&E lead');
assert.equal(personnel.getState().assign('attendance',''),true);
assert.equal(personnel.getState().owners.attendance,'');
personnel.getState().reset();
assert.deepEqual(personnel.getState().owners,{});
console.log('Personnel assignment passed: role guards, trimming, length limit, event history, persistence and reset.');
